import logging
import os
import posixpath
from datetime import datetime
from pathlib import Path
from typing import Any, Iterable, Optional

from .config import Config
from .utils import get_exif_date
from .i18n import _


class ImageScanner:
    SUPPORTED_EXTENSIONS = {
        ".jpg", ".jpeg", ".png", ".tif", ".tiff", ".bmp", ".webp",
        ".heic", ".heif", ".cr2", ".cr3", ".nef", ".dng", ".arw"
    }

    def __init__(self, config: Config):
        self.config = config
        self.logger = logging.getLogger(__name__)

    def _is_image_file(self, path: Path) -> bool:
        return path.suffix.lower() in self.SUPPORTED_EXTENSIONS

    def _get_sort_key(self, path: Path) -> Any:
        """Returns a sort key (EXIF date if available, otherwise modification date)."""
        if self.config.sort_by == "name":
            return path.name.lower()

        exif_date = get_exif_date(path)
        if exif_date is not None:
            return exif_date

        # Fallback: file modification date
        try:
            return datetime.fromtimestamp(path.stat().st_mtime)
        except Exception:
            return datetime.min

    def _is_within(self, path: Path, ancestor: Path, boundary: Path | None = None) -> bool:
        """True if one of the parent folders of `path` (up to `boundary`
        inclusive, without going higher) is physically the same folder as
        `ancestor`, by comparing the real identity of the file (via
        os.path.samefile) rather than a plain textual comparison of the
        paths. Needed notably on Windows: a mapped network drive (e.g.
        Z:\\photos) and its UNC path equivalent (e.g.
        \\\\server\\share\\photos) designate the same physical folder but have
        a totally different textual representation, which Path.resolve() does
        not unify - a purely textual comparison then lets through the files
        already generated by a previous run.

        `boundary` (typically the scanned input folder) stops the climb as
        soon as it leaves it: samefile() makes one system call per level,
        costly on a network share, and useless beyond the input folder since
        no candidate file can be located there. The boundary comparison stays
        purely textual (it only serves to optimise, never to decide the
        exclusion): on failure it merely climbs a little higher, without ever
        compromising the correctness of the result.
        """
        if not ancestor.exists():
            return False
        for parent in path.parents:
            try:
                if os.path.samefile(parent, ancestor):
                    return True
            except OSError:
                continue
            if boundary is not None and parent == boundary:
                break
        return False

    def _included_dirs(self) -> Optional[frozenset]:
        """Selected subfolders (normalised relative paths, "." = the input
        folder itself), or None when all the photos are taken into account
        (historical behaviour). An entry outside the input folder is ignored
        with a warning."""
        wanted = getattr(self.config, "include_dirs", None)
        if wanted is None:
            return None
        kept = set()
        for entry in wanted:
            relative = normalize_include_dir(self.config.input_dir, entry)
            if relative is None:
                self.logger.warning(_("engine.warn_include_dir_outside", dir=entry))
            else:
                kept.add(relative)
        return frozenset(kept)

    def scan(self) -> list[dict]:
        images = []
        # Choosing subfolders implies walking through them: the search is
        # then necessarily recursive, even without the -r option.
        include_dirs = self._included_dirs()
        recursive = self.config.recursive or include_dirs is not None
        pattern = "**/*" if recursive else "*"

        self.logger.info(_("engine.log_scan_folder", dir=self.config.input_dir, recursive=recursive))
        if include_dirs is not None:
            self.logger.info(_("engine.log_include_dirs", count=len(include_dirs)))

        # Subfolders generated by a previous run (planches/, gallery/) to
        # exclude from the scan: otherwise, a new generation in recursive
        # mode - in particular when the output folder is nested inside the
        # input folder, or identical to it - finds and reprocesses its own
        # already generated images. portfolio.pdf and index.csv do not need
        # an equivalent exclusion: their extension matches no supported
        # image format.
        excluded_dirs = []
        output_dir = getattr(self.config, "output_dir", None)
        if output_dir:
            try:
                output_dir_resolved = Path(output_dir).resolve()
                excluded_dirs = [
                    output_dir_resolved / "planches",
                    output_dir_resolved / "gallery",
                ]
            except Exception:
                excluded_dirs = []

        try:
            input_dir_resolved = self.config.input_dir.resolve()
        except OSError:
            input_dir_resolved = None

        skipped_output = 0
        for path in self.config.input_dir.glob(pattern):
            if not path.is_file() or not self._is_image_file(path):
                continue

            # Only the photos located DIRECTLY in one of the selected folders
            # count (not those of their subfolders: each one is ticked
            # separately).
            if include_dirs is not None:
                try:
                    relative_parent = path.parent.relative_to(self.config.input_dir).as_posix()
                except ValueError:
                    continue
                if relative_parent not in include_dirs:
                    continue

            if excluded_dirs:
                resolved_path = path.resolve()
                if any(
                    self._is_within(resolved_path, excl, input_dir_resolved)
                    for excl in excluded_dirs
                ):
                    skipped_output += 1
                    continue

            try:
                sort_key = self._get_sort_key(path)
                images.append({
                    "path": path,
                    "filename": path.name,
                    "sort_key": sort_key,
                })
            except Exception as e:
                self.logger.warning(_("engine.warn_scan_file_failed", name=path.name, error=e))

        # Sorting the images
        images.sort(key=lambda x: x["sort_key"])

        # Adding a sequential number
        for i, item in enumerate(images, 1):
            item["num"] = f"{i:03d}"

        if skipped_output:
            self.logger.info(_("engine.log_skipped_in_output", count=skipped_output))
        self.logger.info(_("engine.log_images_found_sorted", count=len(images)))
        return images


def normalize_include_dir(input_dir: Path, entry) -> Optional[str]:
    """POSIX path of `entry` relative to `input_dir` ("." for the input
    folder itself), or None if it designates a place outside that
    folder. Accepts a relative path (the form produced by
    list_image_folders()) as well as an absolute path located under
    `input_dir`."""
    candidate = Path(str(entry))
    if candidate.is_absolute():
        try:
            candidate = candidate.relative_to(input_dir)
        except ValueError:
            try:
                candidate = candidate.resolve().relative_to(Path(input_dir).resolve())
            except (ValueError, OSError):
                return None
    relative = posixpath.normpath(candidate.as_posix() or ".")
    if relative == ".." or relative.startswith("../") or relative.startswith("/"):
        return None
    return relative


def list_image_folders(input_dir: Path, output_dir: Optional[Path] = None) -> list[tuple[str, int]]:
    """Folders of `input_dir` (itself included) that DIRECTLY contain at
    least one supported photo, with their photo count:
    `[(POSIX relative path, count)]`, "." (the input folder) first, then
    in alphabetical order. This is the list offered to the user to choose
    the subfolders to process (Config.include_dirs).

    Same exclusions as ImageScanner.scan(): the `planches` and `gallery`
    subfolders of the output folder (a previous generation) are never
    offered. Only file names are read - neither EXIF nor opening an
    image -, which stays fast on large photo libraries."""
    input_dir = Path(input_dir)
    excluded = []
    if output_dir:
        try:
            output_resolved = Path(output_dir).resolve()
            excluded = [output_resolved / "planches", output_resolved / "gallery"]
        except OSError:
            excluded = []

    def is_excluded(folder: str) -> bool:
        for excluded_dir in excluded:
            try:
                if excluded_dir.exists() and os.path.samefile(folder, excluded_dir):
                    return True
            except OSError:
                continue
        return False

    extensions = ImageScanner.SUPPORTED_EXTENSIONS
    found: dict[str, int] = {}
    for dirpath, dirnames, filenames in os.walk(input_dir):
        if excluded:
            dirnames[:] = [
                name for name in dirnames
                if not (name in ("planches", "gallery") and is_excluded(os.path.join(dirpath, name)))
            ]
        dirnames.sort(key=str.lower)
        count = sum(1 for name in filenames if Path(name).suffix.lower() in extensions)
        if count:
            relative = os.path.relpath(dirpath, input_dir).replace(os.sep, "/")
            found[relative] = count

    return sorted(found.items(), key=lambda item: (item[0] != ".", item[0].lower(), item[0]))
